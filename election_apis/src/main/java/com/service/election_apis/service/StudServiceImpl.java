package com.service.election_apis.service;

import org.springframework.stereotype.Service;

import com.service.election_apis.entity.TestJ;
import com.service.election_apis.repo.StudRepository;

@Service
public class StudServiceImpl implements StudService{

	private final StudRepository repository;

    public StudServiceImpl(StudRepository repository) {
        this.repository = repository;
    }

    @Override
    public TestJ saveStud(TestJ stud) {

        stud.setIdd(null); // Auto-generated by Hibernate

        return repository.save(stud);
    }

    @Override
    public TestJ getStudById(Integer id) {

        return repository.findById(id)
                .orElseThrow(() ->
                    new RuntimeException("Student not found: " + id));
    }
}
